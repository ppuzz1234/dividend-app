/**
 * 비포함 고지 — 답이 **빠뜨린 것을 스스로 말하게** 한다.
 *
 * 사양 §0-A.7: "비포함 항목을 조용히 빼지 마라 … 결과 출력에 **비포함 사실을 반드시 표기**해야
 * 한다. 표기 없는 '세후 금액'은 거짓이다."
 *
 * ## 왜 만들었나 (실측 2026-08-12)
 * `"연금저축 세액공제율 알려줘"` 에 엔진은 소득세법 제59조의3 제1항의 비율을 **원문 그대로**
 * 답했다. 인용도 붙었고 한 글자도 어긋나지 않았다. 그런데 사용자는 **"틀렸다"** 고 판정했다 —
 * 널리 알려진 수치가 지방소득세까지 더한 값이라 답과 달랐기 때문이다.
 *
 * 「지방세법」은 이 엔진의 수집 대상 법령이 아니다 (`packages/corpus/targets.json` —
 * 소득세법·시행령, 조세특례제한법·시행령, 근로자퇴직급여 보장법·시행령 6건뿐).
 * 즉 **없는 걸 못 말한 게 아니라, 없다는 말을 안 한 것**이 문제였다. 조문에 충실해도 빠진 것을
 * 말하지 않으면 사용자는 시스템이 틀렸다고 결론짓고 떠난다. 표시 취향이 아니라 정확성 문제이고,
 * 사양이 이미 요구하고 있던 것이다.
 *
 * ## 여기에 세법 값은 없다
 * 모든 문구는 **우리 수집 범위에 대한 진술**이지 세율·한도가 아니다(절대 규칙 1 — 세율은
 * 주석·기본값 어디에도 리터럴로 쓰지 않는다). 지방소득세율을 답에 적고 싶으면 방법은 하나뿐이다:
 * 지방세법을 코퍼스에 넣고 조문으로 인용하는 것. 여기에 숫자를 적어 넣는 건 이 시스템이
 * 없애려는 바로 그 가정이다.
 *
 * ponytail: 트리거가 정규식이라 표현이 바뀌면 놓친다. 상한은 "어휘 밖은 고지가 안 붙는다"이고,
 * 업그레이드 경로는 놓친 사례를 이 표에 추가하는 것이다. 놓쳐도 답 자체는 여전히 조문 인용이라
 * 틀린 값이 나가지는 않는다 — 실패 방향이 안전한 쪽이다.
 */

interface Exclusion {
  /** 로그·테스트에서 가리키기 위한 식별자 (ASCII) */
  readonly id: string;
  /** 이 고지가 필요한 답인지 — 답변 본문에서 찾는다 */
  readonly when: RegExp;
  readonly text: string;
}

const EXCLUSIONS: readonly Exclusion[] = [
  {
    // 비율을 말한 순간 사용자는 자기가 아는 "지방소득세 포함" 값과 비교한다.
    id: "LOCAL_INCOME_TAX",
    when: /\d(?:\.\d+)?\s*%|100분의\s*\d/,
    text:
      "이 비율은 소득세법·조세특례제한법 등 국세 기준입니다. " +
      "지방소득세는 「지방세법」 소관이고 이 엔진의 수집 대상 법령이 아니라 반영되어 있지 않습니다 " +
      "— 널리 알려진 수치는 지방소득세를 더한 값이라 이 답과 다를 수 있습니다.",
  },
  {
    // 금융소득·연금수령 질문의 실제 관심사는 대개 건보료인데, 우리는 그 법을 갖고 있지 않다.
    id: "SOCIAL_INSURANCE",
    when: /금융소득|종합과세|연금소득|연금\s*수령/,
    text:
      "건강보험료 등 준조세는 계산·수록 대상이 아닙니다(사양 §0-A.7 v1 비계산 항목). " +
      "「국민건강보험법」도 수집 대상 법령이 아닙니다.",
  },
];

/**
 * 이 답변에 붙어야 하는 비포함 고지들. 없으면 빈 배열.
 * 순서는 표 순서를 따른다 — 같은 답은 매번 같은 고지를 같은 순서로 받아야 재현된다(§1.3).
 */
export function findExclusions(answerText: string): readonly string[] {
  return EXCLUSIONS.filter((e) => e.when.test(answerText)).map((e) => e.text);
}

/** 테스트·디버깅용 — 어떤 규칙에 걸렸는지 */
export function findExclusionIds(answerText: string): readonly string[] {
  return EXCLUSIONS.filter((e) => e.when.test(answerText)).map((e) => e.id);
}
