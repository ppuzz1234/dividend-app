/**
 * Intent Router — FACT 엔진에 **들어가면 안 되는 질문**을 앞에서 걷어낸다 (사양 §13 순서 7).
 *
 * ## 라우터가 지키는 것은 딱 하나다
 * 사양 §1.2 는 `UNMODELED_OFFICIAL_SOURCE` 에 대해 **개인 적용 금지**를 못 박는다.
 * 그런데 "나 연봉 6천인데 IRP 얼마 넣어야 돼?" 를 FACT 엔진에 그대로 넣으면,
 * LLM 은 조문을 읽고 **개인에게 맞춘 답을 쓰려고 한다.** 프롬프트로 막는 건 사후 방어고,
 * 애초에 그 질문이 엔진에 도달하지 않는 것이 사전 방어다. 그게 이 파일이다.
 *
 * ## 왜 LLM 을 안 쓰나
 * 사양 §1.3 재현성 — 같은 질문은 항상 같은 분기로 가야 한다. LLM 분류기는 그 보장이 없다.
 * 그리고 판별을 틀려도 손해가 작다: PLAN 으로 잘못 보내면 "미션 2 미구현" 안내가 나가고
 * 사용자가 다시 물으면 된다. 반대 방향(PLAN 을 FACT 로 흘림)이 위험하므로 **PLAN 쪽으로 기운다.**
 *
 * ## 한국어 부분문자열 함정
 * `내`·`제`·`저` 를 그냥 `includes` 하면 **제55조**·**국내**·**저축**이 전부 걸린다(실측).
 * 그래서 개인 신호는 조사까지 붙은 2글자 이상 토큰으로만 잡는다.
 *
 * ponytail: 규칙 기반이라 새로운 표현은 놓친다. 상한은 "어휘 목록 밖은 FACT 로 샌다"이고,
 * 업그레이드 경로는 오분류 사례를 `docs/ORDER7-OPEN-QUESTIONS.md` 에 모아 목록을 늘리는 것이다.
 * 분류기를 학습시키는 방향은 재현성(§1.3)을 깨므로 택하지 않는다.
 */

export type Intent = "FACT" | "PLAN";

export interface RouteResult {
  readonly intent: Intent;
  /** 어떤 신호에 걸렸는가 — 오분류를 사람이 추적할 수 있어야 목록을 고칠 수 있다 */
  readonly matched: readonly string[];
  /** PLAN 일 때 사용자에게 내보낼 안내. FACT 면 null */
  readonly message: string | null;
}

/**
 * "이 사람 자신의 상황" 신호. 조사까지 포함해 부분문자열 오탐을 막는다.
 * `내가`(O) vs `국내가격`(X), `제가`(O) vs `제55조`(X).
 */
const PERSONAL = [
  "나는", "내가", "나한테", "나에게", "내 경우", "내 나이", "내 소득", "내 연봉",
  "제가", "저는", "저한테", "저에게", "제 경우", "제 나이", "제 소득", "제 연봉",
  "우리집", "저희",
] as const;

/**
 * 개인 소득 진술. **나이와 달리 이건 강한 신호다** — 조문은 "연봉 6000만원"처럼 쓰지 않는다.
 * 반면 나이(`40세 이상`)는 조문의 가입 요건에 흔히 나오므로 아래 WEAK 로 내렸다(실측 오탐).
 */
const PERSONAL_INCOME: readonly RegExp[] = [
  /연봉\s*\d/,
  /월급\s*\d/,
  /소득이\s*\d/,
  // ★ 실측 누락(2026-08-04): `"총급여 5천만원인데 연금저축 600만원 넣으면 세액공제 얼마 받아?"` 가
  //   `나는` 이 없어 FACT 로 샜고, **답이 "90만원이다. 600만원 × 15%" 라고 계산해 버렸다.**
  //   §1.2 개인 적용 금지 + 절대 규칙 3(계산 경로 LLM 금지)을 동시에 어긴 것이다.
  //   조문도 `총급여액 5천만원` 처럼 쓰지만, 조문은 **기준**을 말하고 사용자는 **자기 값**을 말한다 —
  //   그 차이는 아래 `얼마 받` 류의 결과 요구와 함께 나타난다. 그래서 이 패턴만으로는 PLAN 으로 보내지 않고
  //   **약한 신호**로 두고, 결과 요구(ADVISORY)와 겹칠 때 걷어낸다.
];

/**
 * 개인 수치처럼 보이지만 **조문에도 흔한** 표현 — 혼자서는 PLAN 이 아니다.
 * `"총급여 5천만원 이하면 공제율이 몇 퍼센트인가"` 는 조문의 **기준**을 묻는 FACT 질의다.
 *
 * ⚠️ 패턴을 여러 개로 쪼개면 안 된다 — `총급여\s*\d` 와 `급여\s*\d` 가 **같은 자리**를 각각
 *   세어 약한 신호 2개가 되고, 그러면 위 FACT 질의가 PLAN 으로 걷힌다(실측).
 *   하나의 교대 패턴으로 묶어 **한 자리는 한 번만** 세게 한다.
 */
const WEAK_INCOME: readonly RegExp[] = [/(?:총급여|급여|연소득|종합소득금액)\s*\d/];

/** 나이 진술 + 상황 서술 어미. 조문의 연령 요건과 구별되게 어미까지 붙은 것만 강한 신호로 본다. */
const PERSONAL_SITUATION = ["살인데", "세인데", "살이고", "세이고", "살이라", "세이라"] as const;

/**
 * 약한 신호 — 이것만으로는 PLAN 으로 안 보낸다.
 * `40세 이상 가입 제한이 있나`(조문 질의)와 `저 40세인데`(개인 질의)가 같은 패턴에 걸리기 때문.
 * 다른 신호와 **2개 이상 겹칠 때만** PLAN 이다.
 */
const WEAK_NUMERIC: readonly RegExp[] = [/\d+\s*살/, /\d+\s*세(?![가-힣])/];

/**
 * 조언·설계 요구 신호. 이 어휘가 있으면 **개인 신호가 없어도 PLAN 이다** —
 * "ISA 랑 IRP 중 뭐가 유리해?" 는 주어가 없어도 최적화 질문이다.
 * §4.4 금지 문구(`가장 최적의`)와 같은 계열임에 주의.
 */
const ADVISORY = [
  "추천", "유리한", "유리해", "유리할", "유리함", "최적", "가장 좋",
  "어느 게 나", "뭐가 나", "어떤 게 나", "낫나", "나을까",
  "얼마나 넣", "얼마 넣", "얼마를 넣", "얼마씩", "얼마나 저축",
  // ★ **결과 금액**을 요구하는 말. `"한도가 얼마인가"`(제도 조회)와 달리 **계산을 시킨다.**
  //   실측: `"세액공제 얼마 받아?"` 가 안 걸려 답이 90만원을 계산했다.
  "얼마 받", "얼마나 받", "얼마 돌려받", "얼마 공제", "얼마나 공제", "얼마 절세", "얼마나 절세",
  "얼마 내야", "얼마 나와", "얼마가 되",
  "어떻게 해야", "어떻게 하는 게", "짜줘", "설계해", "플랜", "전략",
  "절세 방법", "절세하려면", "아끼려면",
] as const;

const PLAN_MESSAGE =
  "이 질문은 개인 상황에 맞춘 계좌 선택·저축 설계를 요구합니다. " +
  "그 판단은 검증된 정책 규칙 위에서 도는 PLAN 엔진(미션 2)의 몫이며, 아직 구현되지 않았습니다.\n\n" +
  "지금 이 엔진(FACT)은 법령 원문 근거만 제공합니다. 개인 수치를 빼고 제도 자체를 물어보시면 " +
  '조문과 시행일을 붙여 답합니다. 예: "IRP 연간 납입한도가 얼마인가", "ISA 중도해지 시 과세 방법".';

export function routeIntent(query: string): RouteResult {
  const q = query.trim();
  const strong: string[] = [];
  const weak: string[] = [];

  for (const t of [...PERSONAL, ...PERSONAL_SITUATION, ...ADVISORY]) if (q.includes(t)) strong.push(t);
  for (const re of PERSONAL_INCOME) {
    const m = re.exec(q);
    if (m !== null) strong.push(m[0].trim());
  }
  for (const re of [...WEAK_NUMERIC, ...WEAK_INCOME]) {
    const m = re.exec(q);
    if (m !== null) weak.push(m[0].trim());
  }

  // 강한 신호 1개면 PLAN. 약한 신호는 혼자서는 못 보내고 2개 이상 겹쳐야 한다.
  const matched = [...strong, ...weak];
  if (strong.length > 0 || matched.length >= 2) {
    return { intent: "PLAN", matched, message: PLAN_MESSAGE };
  }
  return { intent: "FACT", matched: [], message: null };
}

export { PLAN_MESSAGE };
